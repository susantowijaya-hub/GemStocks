function buildSeries(
  base: number,
  end: number,
  seed: number,
  volatility = 0.012
): Record<Timeframe, number[]> {
  const make = (points: number, startOffset: number, amp: number) => {
    const arr: number[] = [];
    const startVal = end * (1 - startOffset);
    for (let i = 0; i < points; i++) {
      const t = i / (points - 1);
      const wave =
        Math.sin((t * 3.4 + seed) * Math.PI) * amp +
        Math.cos((t * 6.8 + seed * 1.7) * Math.PI) * (amp * 0.45);
      const val = startVal + (end - startVal) * t + end * wave;
      arr.push(Number(val.toFixed(4)));
    }
    arr[0] = Number(startVal.toFixed(4));
    arr[arr.length - 1] = Number(end.toFixed(4));
    return arr;
  };

  const dayDiff = (end - base) / Math.max(base, 0.0001);
  return {
    '1D': make(24, dayDiff, volatility * 0.45),
    '1W': make(24, dayDiff * 2.2, volatility * 0.8),
    '1M': make(24, 0.032, volatility * 1.3),
    '3M': make(24, 0.068, volatility * 1.8),
    YTD: make(24, 0.14, volatility * 2.1),
    '1Y': make(24, 0.19, volatility * 2.4),
    ALL: make(24, 0.35, volatility * 2.9),
  };
}

